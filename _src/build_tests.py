"""Agrikranti: _src/questions/tNN.txt  ->  tests.js
Line 1:  TITLE|Test N - Topic, Topic
Har agla line ek prashn:  question||opt1||opt2||opt3||opt4||A/B/C/D||explanation
Run (repo root se):  python3 _src/build_tests.py
"""
import glob, json, os, random, re, sys
from collections import Counter
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tests = []
for f in sorted(glob.glob(os.path.join(root, '_src', 'questions', 't[0-9][0-9].txt'))):
    lines = [l.rstrip('\n') for l in open(f, encoding='utf-8') if l.strip()]
    assert lines[0].startswith('TITLE|'), f + ': first line must be TITLE|...'
    title = lines[0].split('|', 1)[1]
    qs = []
    for n, l in enumerate(lines[1:], 2):
        p = [x.strip() for x in l.split('||')]
        assert len(p) == 7, '%s line %d: %d parts (7 chahiye)' % (f, n, len(p))
        assert p[5] in ('A', 'B', 'C', 'D'), '%s line %d: answer letter galat' % (f, n)
        assert len(set(p[1:5])) == 4, '%s line %d: options repeat' % (f, n)
        opts = p[1:5]; ans = opts['ABCD'.index(p[5])]
        r = random.Random(sum(map(ord, p[0])) + n); r.shuffle(opts)
        if any(x.startswith(('दोनों', 'सभी', 'कोई नहीं')) for x in opts): opts = p[1:5]
        qs.append({'q': p[0], 'o': opts, 'a': opts.index(ans), 'e': p[6]})
    tid = 'T' + str(int(re.search(r't(\d+)\.txt$', f).group(1)))
    tests.append({'id': tid, 'title': title, 'questions': qs})
    print(os.path.basename(f), tid, len(qs), 'questions', dict(Counter(q['a'] for q in qs)))
out = os.path.join(root, 'tests.js')
open(out, 'w', encoding='utf-8').write('/* Agrikranti - Test Series data (auto-generated by _src/build_tests.py) */\nwindow.TESTS = '
    + json.dumps(tests, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('tests.js likha gaya:', len(tests), 'tests')
